const Database = require('better-sqlite3');
const db = new Database('../output/fyp2.db', { readonly: true });
const id = 'scan_071acf77-ec5f-4f0e-8e3f-583ef48fc8dd';
const cfg = db.prepare('SELECT config FROM scan_configs WHERE scan_id=?').get(id);
