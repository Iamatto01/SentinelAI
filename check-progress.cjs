const Database = require('better-sqlite3');
const db = new Database('../output/fyp2.db', { readonly: true });
const id = 'scan_071acf77-ec5f-4f0e-8e3f-583ef48fc8dd';
const s = db.prepare('SELECT status, progress, whitebox_meta FROM scans WHERE id=?').get(id);
console.log('STATUS:', s.status, 'progress:', s.progress);
const meta = JSON.parse(s.whitebox_meta || '{}');
console.log('totalFiles:', meta.totalFiles);
console.log('--- PASSES ---');
(meta.passes || []).forEach(p => console.log(`  [${p.status}] ${p.tool} (${p.type}): ${p.findings}${p.error ? ' ERR:' + p.error.slice(0,80) : ''}`));
console.log('--- FINDING COUNT ---');
console.log('findings:', db.prepare('SELECT COUNT(*) c FROM findings WHERE scan_id=?').get(id).c);
db.close();